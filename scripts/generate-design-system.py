def camel(name: str) -> str:
    parts = re.split(r"[-_ ]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def upper_camel(name: str) -> str:
    c = camel(name)
    return c[:1].upper() + c[1:]


def num(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int) or (isinstance(value, float) and value.is_integer()):
        return str(int(value))
    return repr(round(value, 4))


def hex_literal(value: str) -> str:
    return "0x" + value.lstrip("#").upper()


def color_line(name: str, value: str, opacity=None, doc=None) -> str:
    lines = []
    if doc:
        lines.append(f"    /// {doc}")
    if opacity is None:
        lines.append(f"    static let {name} = Color(taleedHex: {hex_literal(value)})")
    else:
        lines.append(f"    static let {name} = Color(taleedHex: {hex_literal(value)}, opacity: {num(opacity)})")
    return "\n".join(lines)


def parse_colour(text: str):
    """`#11182D at 80 %` is ("#11182D", 0.8); `#FFFFFF` is ("#FFFFFF", None); anything else is None."""
    m = re.fullmatch(r"\s*(#[0-9A-Fa-f]{6})(?:\s+at\s+(\d+)\s*%)?\s*(?:\(.*\))?\s*", text)
    if not m:
        return None
    return m.group(1).upper(), (int(m.group(2)) / 100 if m.group(2) else None)


def read_dark_palette(path: Path) -> dict:
    """The palette table of dark-mode.md: name -> (light text, dark colour, dark opacity, notes)."""
    palette = {}
    for line in path.read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3:
            continue
        m = re.fullmatch(r"\**`([A-Za-z]+)`\**(?:\s*\(new role\))?", cells[0])
        if not m:
            continue
        dark = parse_colour(cells[2])
        if dark is None:
            raise SystemExit(f"dark-mode.md: no dark colour for {m.group(1)}: {cells[2]!r}")
        palette[m.group(1)] = (cells[1], dark[0], dark[1], cells[3] if len(cells) > 3 else "")
    return palette


def dynamic_line(name: str, light: str, light_opacity, dark: str, dark_opacity, doc=None) -> str:
    lines = [f"    /// {doc}"] if doc else []
    args = f"taleedLight: {hex_literal(light)}"
    if light_opacity is not None:
        args += f", lightOpacity: {num(light_opacity)}"
    args += f", dark: {hex_literal(dark)}"
    if dark_opacity is not None:
        args += f", darkOpacity: {num(dark_opacity)}"
    lines.append(f"    static let {name} = Color({args})")
    return "\n".join(lines)


def is_token(spec: dict) -> bool:
    """False for values tokens.json keeps only as a record (`phosphorDefault`: "Treat as a Figma leftover, not a token")."""
    return "not a token" not in str(spec.get("usedFor", ""))


def gen_colors(color: dict, dark: dict) -> str:
    out = ["/// Colours: the scales, the semantic colours (Figma variables) and the recurring literals.",
           "/// `color.blue.500` is `TaleedColor.blue500`, `color.semantic.brandPrimary` is `TaleedColor.brandPrimary`,",
           "/// `color.literal.brandSoft` is `TaleedColor.brandSoft`.",
           "/// The scales are fixed. Every semantic and literal colour has a light value (tokens.json, Figma) and a",
           "/// dark value (dark-mode.md): it follows the colour scheme of the view that draws it.",
           "enum TaleedColor {"]
    scale_hex = {}
    for scale in ["blue", "mint", "navy", "neutral"]:
        out.append(f"    // MARK: {scale}")
        for step, value in color[scale].items():
            if step.startswith("$"):
                continue
            scale_hex[f"{scale}.{step}"] = value
            out.append(color_line(f"{scale}{step}", value))
    used_dark = set()
    # name -> (light hex, light opacity, dark hex, dark opacity), for the catalog.
    values = {}

    def emit(name, light, light_opacity, doc):
        if name in dark:
            _, dark_hex, dark_opacity, _ = dark[name]
            used_dark.add(name)
            values[name] = (light, light_opacity, dark_hex, dark_opacity)
            out.append(dynamic_line(name, light, light_opacity, dark_hex, dark_opacity, doc=doc))
        else:
            values[name] = (light, light_opacity, light, light_opacity)
            out.append(color_line(name, light, light_opacity, doc=(doc.rstrip(".") + ". Same in dark.") if doc else "Same in dark."))

    out.append("")
    out.append("    // MARK: Semantic")
    for name, spec in color["semantic"].items():
        if name.startswith("$"):
            continue
        ref = spec.get("ref")
        doc = f"`{spec['figma']}` {spec['value']}"
        if ref and re.fullmatch(r"[a-z]+\.\d+", ref):
            doc += f" (`{ref}` in light)"
        emit(name, spec["value"], None, doc + ".")
    out.append("")
    out.append("    // MARK: Literals (no Figma variable)")
    for name, spec in color["literal"].items():
        if name.startswith("$") or not is_token(spec):
            continue
        emit(name, spec["value"], spec.get("opacity"), spec.get("usedFor"))
    out.append("")
    out.append("    // MARK: Dark-mode roles (dark-mode.md, no Figma variable)")
    roles = [n for n in dark if n not in values]
    for name in roles:
        light_text, _, _, notes = dark[name]
        if name in AS_TODAY and AS_TODAY[name] in scale_hex:
            light, light_opacity = scale_hex[AS_TODAY[name]], None
        elif name in AS_TODAY:
            light, light_opacity = values[AS_TODAY[name]][0], values[AS_TODAY[name]][1]
        else:
            parsed = parse_colour(light_text)
            if parsed is None:
                raise SystemExit(f"dark-mode.md: no light colour for the new role {name}: {light_text!r}")
            light, light_opacity = parsed
        emit(name, light, light_opacity, (notes[:1].upper() + notes[1:] + ".") if notes else "dark-mode.md role.")
    missing = set(dark) - used_dark
    if missing:
        raise SystemExit(f"dark-mode.md names unknown colours: {sorted(missing)}")
    out.append("")
    out.append("    /// Every colour token by group and name, with its light and dark values (for the gallery and token tests).")
    out.append("    static let catalog: [ColorToken] = [")
    for scale in ["blue", "mint", "navy", "neutral"]:
        for step, value in color[scale].items():
            if step.startswith("$"):
                continue
            out.append(f"        ColorToken(group: \"{scale}\", name: \"{scale}{step}\", color: {scale}{step}, "
                       f"hex: {hex_literal(value)}, opacity: 1, darkHex: {hex_literal(value)}, darkOpacity: 1),")
    groups = [("semantic", [n for n in color["semantic"] if not n.startswith("$")]),
              ("literal", [n for n, spec in color["literal"].items() if not n.startswith("$") and is_token(spec)]),
              ("dark", roles)]
    for group, names in groups:
        for name in names:
            light, light_opacity, dark_hex, dark_opacity = values[name]
            out.append(f"        ColorToken(group: \"{group}\", name: \"{name}\", color: {name}, hex: {hex_literal(light)}, "
                       f"opacity: {num(light_opacity if light_opacity is not None else 1)}, darkHex: {hex_literal(dark_hex)}, "
                       f"darkOpacity: {num(dark_opacity if dark_opacity is not None else 1)}),")
    out.append("    ]")
    out.append("}")
    out.append("")
    out.append("/// A colour token with its light (tokens.json) and dark (dark-mode.md) values.")
    out.append("struct ColorToken: Sendable {")
    out.append("    let group: String")
    out.append("    let name: String")
    out.append("    let color: Color")
    out.append("    let hex: UInt32")
    out.append("    let opacity: Double")
    out.append("    let darkHex: UInt32")
    out.append("    let darkOpacity: Double")
    out.append("}")
    return "\n".join(out)


def relative_style(size: float) -> str:
    return min(DYNAMIC_TYPE, key=lambda item: (abs(item[1] - size), item[0] != "body"))[0]


def text_style(name: str, spec: dict) -> str:
    size = spec["fontSize"]
    weight = WEIGHTS[spec["fontWeight"]]
    line = spec.get("lineHeight", {})
    figma_line = line.get("figma")
    line_height = "nil" if figma_line == "AUTO" else num(line["px"])
    tracking = spec.get("letterSpacing", {}).get("px", 0)
    doc = spec.get("figmaStyle") or spec.get("usedFor") or ""
    return (f"    /// {doc}: {num(size)}/{spec['fontWeight']}, line {figma_line}.\n"
            f"    static let {name} = TaleedTextStyle(\n"
            f"        size: {num(size)}, weight: .{weight}, lineHeight: {line_height}, letterSpacing: {num(tracking)},\n"
            f"        relativeTo: .{relative_style(size)}\n"
            f"    )")


def gen_typography(typo: dict) -> str:
    out = ["/// Text styles. Figma styles first, then the recurring settings without a style (`typography.derived`).",
           "/// Apply one with `.taleedFont(TaleedFont.title1)`: Plus Jakarta Sans, with Alexandria as the cascade for Arabic script.",
           "enum TaleedFont {"]
    for name, spec in typo.items():
        if name.startswith("$") or name == "derived":
            continue
        out.append(text_style(name, spec))
    out.append("")
    out.append("    // MARK: Derived (no Figma style)")
    for name, spec in typo["derived"].items():
        if name.startswith("$"):
            continue
        out.append(text_style(name, spec))
    names = [n for n in typo if not n.startswith("$") and n != "derived"] + \
            [n for n in typo["derived"] if not n.startswith("$")]
    out.append("")
    out.append("    /// Every text style by name (for the gallery and token tests).")
    out.append("    static let catalog: [(name: String, style: TaleedTextStyle)] = [")
    for n in names:
        out.append(f"        (\"{n}\", {n}),")
    out.append("    ]")
    out.append("}")
    return "\n".join(out)


def gen_simple(enum: str, doc: str, values: dict, prefix: str = "", type_name: str = "CGFloat") -> str:
    out = [f"/// {doc}", f"enum {enum} {{"]
    for key, value in values.items():
        if key.startswith("$") or not isinstance(value, (int, float)):
            continue
        out.append(f"    static let {prefix}{camel(key)}: {type_name} = {num(value)}")
    entries = [(k, v) for k, v in values.items() if not k.startswith("$") and isinstance(v, (int, float))]
    out.append("")
    out.append(f"    static let catalog: [(name: String, value: {type_name})] = [")
    for k, _ in entries:
        out.append(f"        (\"{prefix}{camel(k)}\", {prefix}{camel(k)}),")
    out.append("    ]")
    out.append("}")
    return "\n".join(out)


def gen_elevation(elevation: dict) -> str:
    out = ["/// Shadows. `level0` is a 1 pt `borderSubtle` border without shadow: use `.taleedBorder()`.",
           "/// In dark the shadow is black, so it never shows as a light halo (dark-mode.md).",
           "/// Blur is the Figma (CSS) blur; `TaleedShadow` halves it for SwiftUI's radius.",
           "enum TaleedElevation {"]
    for name, spec in elevation.items():
        if name.startswith("$") or not isinstance(spec, dict) or not spec.get("shadow"):
            continue
        s = spec["shadow"]
        out.append(f"    static let {name} = TaleedShadow(x: {num(s['x'])}, y: {num(s['y'])}, blur: {num(s['blur'])}, "
                   f"color: Color(taleedLight: {hex_literal(s['color'])}, dark: {hex_literal(DARK_SHADOW)}), opacity: {num(s['opacity'])})")
    out.append("}")
    return "\n".join(out)


def flat_entries(values: dict, prefix: str = "") -> list:
    """Flattens a token group into (lowerCamelCase name, value) pairs: `size.button.small.height` is
    `buttonSmallHeight`, as tokens.json's naming rule says (the same names as the Android app).
    A "24/20" padding becomes `…PaddingY` and `…PaddingX`."""
    out = []
    for key, value in values.items():
        if key.startswith("$") or key in ("note", "provenance"):
            continue
        name = prefix + (key[:1].upper() + key[1:] if prefix else key)
        name = camel(name) if not prefix else name
        if isinstance(value, dict):
            keys = set(k for k in value if not k.startswith("$") and k != "note")
            if keys == {"value"}:
                out.append((name, value["value"]))
            else:
                out.extend(flat_entries(value, name))
        elif isinstance(value, str) and re.fullmatch(r"\d+(\.\d+)?/\d+(\.\d+)?", value):
            y, x = value.split("/")
            out.append((name + "Y", float(y)))
            out.append((name + "X", float(x)))
        else:
            out.append((name, value))
    return out


def gen_flat(enum: str, doc: str, values: dict) -> str:
    out = [f"/// {doc}", f"enum {enum} {{"]
    for name, value in flat_entries(values):
        if isinstance(value, bool):
            out.append(f"    static let {name} = {num(value)}")
        elif isinstance(value, int) and name.lower().endswith(("columns", "photos", "placeholders")):
            out.append(f"    static let {name} = {num(value)}")
        elif isinstance(value, (int, float)):
            out.append(f"    static let {name}: CGFloat = {num(value)}")
        elif isinstance(value, str) and value.startswith("radius."):
            out.append(f"    static let {name} = TaleedRadius.{value.split('.')[1]}")
    out.append("}")
    return "\n".join(out)


def gen_motion(motion: dict) -> str:
    out = ["/// Motion. Durations in seconds (tokens.json gives milliseconds). Respect Reduce Motion.",
           "enum TaleedMotion {"]
    for key, value in motion.items():
        if key.startswith("$") or value is None:
            continue
        if isinstance(value, bool):
            out.append(f"    static let {key} = {num(value)}")
        elif key.endswith("Placeholders"):
            out.append(f"    static let {key} = {num(value)}")
        else:
            out.append(f"    static let {key}: TimeInterval = {num(value / 1000)}")
    out.append("}")
    return "\n".join(out)


def generate_tokens(tokens: dict, dark: dict) -> None:
    parts = [
        HEADER,
        "// swiftlint:disable identifier_name file_length line_length",
        "import SwiftUI",
        "",
        gen_colors(tokens["color"], dark),
        "",
        gen_typography(tokens["typography"]),
        "",
        gen_simple("TaleedSpacing", "Spacing scale (4 pt base). `spacing.16` is `TaleedSpacing.s16`.",
                   tokens["spacing"], prefix="s"),
        "",
        gen_simple("TaleedRadius", "Corner radii. `full` is for pills, avatars and toggles.", tokens["radius"]),
        "",
        gen_elevation(tokens["elevation"]),
        "",
        gen_simple("TaleedOpacity", "Opacities.", tokens["opacity"], type_name="Double"),
        "",
        gen_flat("TaleedSize", "Component sizes, from `size` in tokens.json, flattened: `size.button.small.height` is "
                 "`TaleedSize.buttonSmallHeight`.", tokens["size"]),
        "",
        gen_flat("TaleedLayout", "Screen layout, from `layout` in tokens.json, flattened: `layout.pageHeadingPadding.top` "
                 "is `TaleedLayout.pageHeadingPaddingTop`.", tokens["layout"]),
        "",
        gen_motion(tokens["motion"]),
        "// swiftlint:enable identifier_name file_length line_length",
        "",
    ]
    TOKENS_OUT.parent.mkdir(parents=True, exist_ok=True)
    TOKENS_OUT.write_text("\n".join(parts))


def write_json(path: Path, data: dict) -> None:
    path.mkdir(parents=True, exist_ok=True) if path.suffix == "" else None
    path.write_text(json.dumps(data, indent=2) + "\n")


def folder(path: Path, namespace: bool) -> None:
    path.mkdir(parents=True, exist_ok=True)
    data = {"info": {"author": "xcode", "version": 1}}
    if namespace:
        data["properties"] = {"provides-namespace": True}
    (path / "Contents.json").write_text(json.dumps(data, indent=2) + "\n")


def imageset(path: Path, source: Path, template: bool, scale, dark=None) -> None:
    """`dark` is (source, colour replacements) for a vector image's dark appearance."""
    path.mkdir(parents=True, exist_ok=True)
    properties = {}
    if scale is None:
        filename = source.name
        shutil.copy(source, path / filename)
        images = [{"filename": filename, "idiom": "universal"}]
        if dark:
            dark_source, replacements = dark
            # Sources are relative to design/assets, two levels above the source file.
            svg = (source.parents[1] / dark_source).read_text()
            for old, new in replacements.items():
                svg = svg.replace(old, new).replace(old.lower(), new)
            dark_name = source.stem + "-dark.svg"
            (path / dark_name).write_text(svg)
            images.append({"appearances": [{"appearance": "luminosity", "value": "dark"}],
                           "filename": dark_name, "idiom": "universal"})
        properties["preserves-vector-representation"] = True
    elif scale == "sky":
        # 3000 x 4000 opaque PNG: aspect-fill on the tallest phone at 3x needs 2868 px of height.
        filename = path.name + ".jpg"
        subprocess.run(["sips", "-s", "format", "jpeg", "-s", "formatOptions", "82", "-Z", "2868",
                        str(source), "--out", str(path / filename)], check=True, capture_output=True)
        images = [{"filename": filename, "idiom": "universal"}]
    else:
        filename = path.name + source.suffix
        shutil.copy(source, path / filename)
        images = [{"filename": filename, "idiom": "universal"}] if scale == "1x" else [
            {"filename": filename, "idiom": "universal", "scale": scale}]
        if dark:
            dark_source = source.parents[1] / dark[0]
            dark_name = path.stem + "-dark" + dark_source.suffix
            shutil.copy(dark_source, path / dark_name)
            entry = {"appearances": [{"appearance": "luminosity", "value": "dark"}], "filename": dark_name, "idiom": "universal"}
            if scale != "1x":
                entry["scale"] = scale
            images.append(entry)
    if template:
        properties["template-rendering-intent"] = "template"
    data = {"images": images, "info": {"author": "xcode", "version": 1}}
    if properties:
        data["properties"] = properties
    (path / "Contents.json").write_text(json.dumps(data, indent=2) + "\n")


def generate_assets(design: Path, glyphs: dict) -> None:
    if CATALOG.exists():
        shutil.rmtree(CATALOG)
    folder(CATALOG, namespace=False)
    folder(CATALOG / "Icons", namespace=True)
    for glyph in glyphs:
        imageset(CATALOG / "Icons" / f"{glyph}.imageset", design / "assets/icons" / f"{glyph}.svg", True, None)
    for group in sorted({g for g, *_ in IMAGES}):
        folder(CATALOG / group, namespace=True)
    for group, name, source, template, scale in IMAGES:
        imageset(CATALOG / group / f"{name}.imageset", design / "assets" / source, template, scale, DARK_IMAGES.get(name))

    cases = []
    for glyph, weight in glyphs.items():
        cases.append(f"    /// Phosphor {upper_camel(glyph)}, {weight}.")
        cases.append(f"    case {camel(glyph)} = \"{glyph}\"")
    directional = ", ".join("." + camel(g) for g in sorted(DIRECTIONAL_ICONS) if g in glyphs)
    swift = f"""{HEADER}
/// The {len(glyphs)} Phosphor icons of the design system, in the asset catalog under `Icons/`.
/// Draw one with `TaleedIconView(.heart, size: 20, color: TaleedColor.brandPrimary)`.
enum TaleedIcon: String, CaseIterable, Sendable {{
{chr(10).join(cases)}

    /// The asset catalog name.
    var assetName: String {{ "Icons/\\(rawValue)" }}

    /// Icons that point in the reading direction mirror in right-to-left languages.
    var isDirectional: Bool {{
        switch self {{
        case {directional}: true
        default: false
        }}
    }}
}}
"""
    ICONS_OUT.parent.mkdir(parents=True, exist_ok=True)
    ICONS_OUT.write_text(swift)


def copy_fonts(design: Path) -> None:
    if FONTS_OUT.exists():
        shutil.rmtree(FONTS_OUT)
    FONTS_OUT.mkdir(parents=True)
    for family in FONT_FAMILIES.values():
        for weight in FONT_WEIGHTS:
            shutil.copy(design / "fonts/static" / f"{family}-{weight}.ttf", FONTS_OUT)
    for license_file in LICENSES:
        shutil.copy(design / "fonts" / license_file, FONTS_OUT)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--design", required=True, help="the design hand-off folder (with tokens.json)")
    args = parser.parse_args()
    design = Path(args.design).resolve()
    tokens = json.loads((design / "tokens.json").read_text())
    generate_tokens(tokens, read_dark_palette(design / "dark-mode.md"))
    generate_assets(design, tokens["icon"]["glyphs"])
    copy_fonts(design)
    print(f"Wrote {TOKENS_OUT.relative_to(ROOT)}, {ICONS_OUT.relative_to(ROOT)}, "
          f"{CATALOG.relative_to(ROOT)} and {FONTS_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
